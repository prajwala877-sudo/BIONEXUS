// Helper to generate 8-day time series points (May 8 - May 15) with realistic baseline variations and anomalies
function generateTimeSeries(
  baseMean: number,
  sd: number,
  anomalyDayIndices: number[] = [],
  anomalyMagnitudes: number[] = []
) {
  const dates = [
    'May 8',
    'May 9',
    'May 10',
    'May 11',
    'May 12',
    'May 13',
    'May 14',
    'May 15',
  ];

  // Provide realistic natural day-to-day drift
  const defaultFluctuations = [-0.2, 0.3, 0.1, -0.4, 0.2, 0.5, -0.3, 0.1];

  return dates.map((dateLabel, idx) => {
    let val = baseMean + defaultFluctuations[idx] * sd;
    let isAnomaly = false;
    let anomalyReason: string | undefined = undefined;

    const anomalyIdx = anomalyDayIndices.indexOf(idx);
    if (anomalyIdx !== -1) {
      const mag = anomalyMagnitudes[anomalyIdx];
      val = baseMean + mag * sd;
      isAnomaly = Math.abs(val - baseMean) > 2 * sd;
      if (isAnomaly) {
        anomalyReason =
          mag > 0
            ? `Value (${val.toFixed(1)}) exceeded +2 SD upper threshold`
            : `Value (${val.toFixed(1)}) dropped below -2 SD lower threshold`;
      }
    }

    const deviationSD = Number(((val - baseMean) / sd).toFixed(2));

    return {
      timestamp: `2025-05-${8 + idx}T10:00:00Z`,
      dateLabel,
      value: Number(val.toFixed(1)),
      isAnomaly,
      deviationSD,
      anomalyReason,
    };
  });
}

